/** Las filas del catálogo con el nombre del idioma. Las que no están en la lista quedan como vinieron. */
export function conNombresEn<F>(filas: F[]): F[] {
  return filas.map((f) => {
    const x = f as { id?: unknown; nombre?: unknown; creado_por?: unknown };
    const en = typeof x.id === 'string' && x.creado_por == null ? NOMBRES_EN[x.id] : undefined;
    return en && typeof x.nombre === 'string' ? ({ ...f, nombre: en } as F) : f;
  });
}
